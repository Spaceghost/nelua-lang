// Foreign TextMate/Oniguruma engine probe. Maintained grammar data/tooling is Lua.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const modules = process.env.NELUA_TEXTMATE_MODULES;
assert(modules, 'NELUA_TEXTMATE_MODULES must name the pinned test dependency directory');
const tm = require(path.join(modules, 'node_modules/vscode-textmate'));
const onig = require(path.join(modules, 'node_modules/vscode-oniguruma'));
assert.equal(require(path.join(modules, 'node_modules/vscode-textmate/package.json')).version, '9.2.0');
assert.equal(require(path.join(modules, 'node_modules/vscode-oniguruma/package.json')).version, '2.0.1');
(async () => {
  const wasm = fs.readFileSync(path.join(modules, 'node_modules/vscode-oniguruma/release/onig.wasm'));
  await onig.loadWASM(wasm.buffer.slice(wasm.byteOffset, wasm.byteOffset + wasm.byteLength));
  const raw = fs.readFileSync('syntaxes/nelua.tmLanguage.json', 'utf8');
  const registry = new tm.Registry({
    onigLib: Promise.resolve({createOnigScanner: sources => new onig.OnigScanner(sources), createOnigString: s => new onig.OnigString(s)}),
    loadGrammar: async scope => scope === 'source.nelua' ? tm.parseRawGrammar(raw, 'nelua.tmLanguage.json') : null,
  });
  const grammar = await registry.loadGrammar('source.nelua');
  const line = (s, stack = tm.INITIAL) => grammar.tokenizeLine(s, stack);
  const scopeAt = (result, index, scope) => result.tokens.some(t => t.startIndex <= index && t.endIndex > index && t.scopes.includes(scope));
  let s = "global Bytes: type <cimport,nodecl,codename 'const uint8_t*'> = @*[0]uint8";
  let result = line(s);
  assert(scopeAt(result, 0, 'storage.modifier.nelua'));
  assert(scopeAt(result, s.indexOf('cimport'), 'entity.other.attribute-name.nelua'));
  assert(scopeAt(result, s.indexOf("'const"), 'string.quoted.single.nelua'));
  result = line('local function check(record: *uint8): boolean <cexport>');
  assert(scopeAt(result, 15, 'entity.name.function.nelua'));
  assert(!scopeAt(result, 21, 'storage.type.nelua'), 'record is contextual, not a reserved name');
  result = line('--[==[ long comment');
  result = line('local amount = 3 ]=] still comment', result.ruleStack);
  assert(scopeAt(result, 0, 'comment.block.nelua'));
  result = line(']==] local amount = 0xff_u32', result.ruleStack);
  assert(scopeAt(result, 5, 'storage.modifier.nelua'));
  assert(scopeAt(result, 20, 'constant.numeric.nelua'));
  s = "local message = '-- not a comment'"; result = line(s);
  assert(scopeAt(result, s.indexOf('--'), 'string.quoted.single.nelua'));
  assert(!scopeAt(result, s.indexOf('--'), 'comment.line.double-dash.nelua'));
  result = line('##[=[ local lua = true');
  result = line(']=] local amount = 1', result.ruleStack);
  assert(scopeAt(result, 4, 'storage.modifier.nelua'));
  result = line('local bytes = [==[ text');
  result = line(']=] not closed', result.ruleStack);
  assert(scopeAt(result, 0, 'string.quoted.other.long.nelua'));
  result = line(']==] global done = true', result.ruleStack);
  assert(scopeAt(result, 5, 'storage.modifier.nelua'));
  s = 'local bytes: *const [0]cchar = nilptr'; result = line(s);
  assert(scopeAt(result, s.indexOf('const'), 'storage.modifier.const.nelua'));
  assert(scopeAt(result, s.indexOf('cchar'), 'storage.type.nelua'));
  assert(scopeAt(result, s.indexOf('nilptr'), 'constant.language.nelua'), 'type context ends at =');
  s = 'local arr: *const [0]cchar|string = nilptr'; result = line(s);
  assert(scopeAt(result, s.indexOf('|'), 'keyword.operator.type.variant.nelua'), 'brackets stay balanced inside a type context');
  s = 'local pp: *const *const uint8 = nilptr'; result = line(s);
  assert(scopeAt(result, s.lastIndexOf('const'), 'storage.modifier.const.nelua'));
  s = 'local v: integer|string|boolean = 1'; result = line(s);
  assert(scopeAt(result, s.indexOf('|'), 'keyword.operator.type.variant.nelua'));
  assert(scopeAt(result, s.lastIndexOf('|'), 'keyword.operator.type.variant.nelua'));
  s = 'local function pick(x: *const integer|string): boolean|string end'; result = line(s);
  assert(scopeAt(result, s.indexOf('|'), 'keyword.operator.type.variant.nelua'));
  assert(scopeAt(result, s.lastIndexOf('|'), 'keyword.operator.type.variant.nelua'));
  assert(scopeAt(result, s.indexOf('end'), 'keyword.control.nelua'));
  assert(!scopeAt(result, s.indexOf('end'), 'meta.type.annotation.nelua'), 'return type context ends before a statement keyword');
  s = 'local function one(): integer return 1 end'; result = line(s);
  assert(scopeAt(result, s.indexOf('integer'), 'meta.type.annotation.nelua'));
  assert(!scopeAt(result, s.indexOf('return'), 'meta.type.annotation.nelua'), 'return type context ends before return');
  assert(scopeAt(result, s.indexOf('1 end'), 'constant.numeric.nelua'));
  s = 'local V = @variant(integer, string)'; result = line(s);
  assert(scopeAt(result, s.indexOf('variant'), 'storage.type.nelua'));
  s = 'local V = @variant(integer|string, boolean)'; result = line(s);
  assert(scopeAt(result, s.indexOf('|'), 'keyword.operator.type.variant.nelua'), 'nested parentheses keep type rules');
  s = 'local F = @function(integer|string): void'; result = line(s);
  assert(scopeAt(result, s.indexOf('|'), 'keyword.operator.type.variant.nelua'), 'function type arguments keep type rules');
  s = 'local y = x * const'; result = line(s);
  assert(!scopeAt(result, s.indexOf('const'), 'storage.modifier.const.nelua'), 'const after an expression * is a name');
  s = 'local x: integer|string = a | b'; result = line(s);
  assert(scopeAt(result, s.indexOf('|'), 'keyword.operator.type.variant.nelua'));
  assert(!scopeAt(result, s.lastIndexOf('|'), 'keyword.operator.type.variant.nelua'), 'type context ends at =');
  s = "t:insert[[text 1 end]]"; result = line(s);
  assert(scopeAt(result, s.indexOf('text'), 'string.quoted.other.long.nelua'), 'long string after a method call stays a string');
  assert(!scopeAt(result, s.indexOf('end'), 'keyword.control.nelua'));
  result = line('t:insert[==[ first');
  s = 'local still = 1 ]==] local amount = 2'; result = line(s, result.ruleStack);
  assert(scopeAt(result, 0, 'string.quoted.other.long.nelua'), 'multi-line long string after a method call');
  assert(scopeAt(result, s.lastIndexOf('local'), 'storage.modifier.nelua'), 'long string closes at its exact delimiter');
  s = 'local T = @*const uint8|string'; result = line(s);
  assert(scopeAt(result, s.indexOf('const'), 'storage.modifier.const.nelua'));
  assert(scopeAt(result, s.indexOf('|'), 'keyword.operator.type.variant.nelua'));
  s = 'local mask = a | b'; result = line(s);
  assert(scopeAt(result, s.indexOf('|'), 'keyword.operator.nelua'));
  assert(!scopeAt(result, s.indexOf('|'), 'keyword.operator.type.variant.nelua'), 'expression | is not a variant');
  s = 'local const: uint8 <const> = 1'; result = line(s);
  assert(!scopeAt(result, 6, 'storage.modifier.const.nelua'), 'const is contextual, not a reserved name');
  assert(scopeAt(result, s.indexOf('<const') + 1, 'entity.other.attribute-name.nelua'));
  s = 'local x: integer? = 3'; result = line(s);
  assert(scopeAt(result, s.indexOf('?'), 'keyword.operator.type.optional.nelua'), '? after a type is the optional suffix');
  assert(!scopeAt(result, s.indexOf('?'), 'keyword.operator.try.nelua'));
  assert(scopeAt(result, s.indexOf('3'), 'constant.numeric.nelua'), 'type context ends at =');
  s = 'local p: *const R? = nilptr'; result = line(s);
  assert(scopeAt(result, s.indexOf('const'), 'storage.modifier.const.nelua'));
  assert(scopeAt(result, s.indexOf('?'), 'keyword.operator.type.optional.nelua'));
  s = 'local function find(k: integer): integer? return nil end'; result = line(s);
  assert(scopeAt(result, s.indexOf('?'), 'keyword.operator.type.optional.nelua'), 'optional return type');
  assert(scopeAt(result, s.indexOf('return'), 'keyword.control.nelua'));
  s = 'local v = find(k)?'; result = line(s);
  assert(scopeAt(result, s.indexOf('?'), 'keyword.operator.try.nelua'), '? after a call is the try suffix');
  assert(!scopeAt(result, s.indexOf('?'), 'keyword.operator.type.optional.nelua'));
  s = 'f:write(line)?'; result = line(s);
  assert(scopeAt(result, s.indexOf('?'), 'keyword.operator.try.nelua'), 'statement form after a method call');
  assert(!scopeAt(result, s.indexOf('?'), 'keyword.operator.type.optional.nelua'));
  s = 'local q: *[0]cchar? = nilptr'; result = line(s);
  assert(scopeAt(result, s.indexOf('?'), 'keyword.operator.type.optional.nelua'), 'optional array pointer');
  s = 'local z = x? + 1'; result = line(s);
  assert(scopeAt(result, s.indexOf('?'), 'keyword.operator.try.nelua'), '? after a name is the try suffix');
  s = 'local v = x??'; result = line(s);
  assert(scopeAt(result, s.indexOf('?'), 'keyword.operator.try.nelua') && scopeAt(result, s.indexOf('?') + 1, 'keyword.operator.try.nelua'), 'both ? of x?? are try suffixes');
  s = 'local v = x ? + 1'; result = line(s);
  assert(scopeAt(result, s.indexOf('?'), 'keyword.operator.try.nelua'), 'a spaced ? is still the try suffix');
  s = 'local w: integer ? = 1'; result = line(s);
  assert(scopeAt(result, s.indexOf('?'), 'keyword.operator.type.optional.nelua'), 'a spaced ? after a type is the optional suffix');
  assert(!scopeAt(result, s.indexOf('?'), 'keyword.operator.try.nelua'));
  s = 'local d = find(2) orelse 0'; result = line(s);
  assert(scopeAt(result, s.indexOf('orelse'), 'keyword.operator.orelse.nelua'));
  assert(!scopeAt(result, s.indexOf('orelse'), 'keyword.operator.nelua'), 'orelse is not the or operator');
  s = 'if local w = find(1) then'; result = line(s);
  assert(scopeAt(result, 0, 'keyword.control.nelua'));
  assert(scopeAt(result, 3, 'storage.modifier.nelua'));
  assert(scopeAt(result, 3, 'meta.if-local.nelua'), 'if local binding');
  assert(scopeAt(result, s.indexOf('then'), 'keyword.control.nelua'));
  s = 'elseif local u: integer = find(2) then'; result = line(s);
  assert(scopeAt(result, s.indexOf('local'), 'meta.if-local.nelua'), 'elseif local binding');
  assert(scopeAt(result, s.indexOf('integer'), 'meta.type.annotation.nelua'), 'if local keeps the type annotation context');
  assert(scopeAt(result, s.indexOf('then'), 'keyword.control.nelua'));
  registry.dispose();
  console.log('Native TextMate: declarations, annotations, contextual names, typed numbers, exact long delimiters, opaque strings, const pointers, variant types, optionals, try, orelse and if local PASS');
})().catch(error => { console.error(error); process.exitCode = 1; });
